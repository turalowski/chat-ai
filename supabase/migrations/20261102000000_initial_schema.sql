-- Row level security is the single source of truth for who can access what.
-- The anon key is public, so these rules apply to anyone calling Supabase directly.

create table public.documents (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  path text not null unique,
  name text not null check (char_length(name) between 1 and 255),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade
);

create table public.document_groups (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  document_paths text[] not null,
  name text not null check (char_length(name) between 1 and 255),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade
);

alter table public.documents enable row level security;
alter table public.document_groups enable row level security;

-- No update policies exist, so rows can't be changed. Anon keeps select so that its
-- queries return nothing, as there are no policies for it, rather than raising an error.
revoke all on public.documents, public.document_groups from anon, authenticated;
grant select on public.documents, public.document_groups to anon;
grant select, insert, delete on public.documents, public.document_groups to authenticated;

create policy "Users read their documents"
  on public.documents for select to authenticated
  using ((select auth.uid()) = user_id);

-- Registering a path grants chat access to its vectors, so it must be in the user's folder.
create policy "Users add documents from their folder"
  on public.documents for insert to authenticated
  with check (
    (select auth.uid()) = user_id
    and path like (select auth.uid())::text || '/%'
  );

create policy "Users delete their documents"
  on public.documents for delete to authenticated
  using ((select auth.uid()) = user_id);

create policy "Users read their groups"
  on public.document_groups for select to authenticated
  using ((select auth.uid()) = user_id);

create policy "Users add their groups"
  on public.document_groups for insert to authenticated
  with check ((select auth.uid()) = user_id);

create policy "Users delete their groups"
  on public.document_groups for delete to authenticated
  using ((select auth.uid()) = user_id);

-- Storage: a private bucket for PDFs up to 50 MB, with each user's files in their own folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('documents', 'documents', false, 52428800, array['application/pdf']);

create policy "Users read their files"
  on storage.objects for select to authenticated
  using (
    bucket_id = 'documents'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

create policy "Users upload to their folder"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'documents'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

create policy "Users delete their files"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'documents'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );
